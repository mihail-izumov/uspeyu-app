import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { defineConfig } from 'vite'
import vue from '@vitejs/plugin-vue'

/* ── ОПИСАНИЕ ССЫЛКИ — ИЗ ДАННЫХ, А НЕ ИЗ ГОЛОВЫ (Д-73, 16.10.2026) ──────────
 * Слово владельца: заменить «мой расчёт по анализам…» на «Горизонт Михаила
 * 63–70, цель 87 лет». Вилка меняется с новыми анализами, а `index.html`
 * статичен: вписанное руками число осталось бы в превью навсегда, пока на
 * самой главной давно стоит другое. Поэтому в `index.html` стоит метка
 * `__OG_HORIZON__`, а сборка подставляет строку из `public/data/public.json`
 * — того же файла, из которого главная берёт синюю строку первого экрана.
 * Сборка на GitHub идёт из закоммиченного `public.json`, так что превью
 * всегда совпадает с опубликованной главной.
 * ⚠ Ссылок в описании быть не может: мессенджеры показывают его простым
 *   текстом. Нет данных — строка без чисел, но метка наружу не уезжает. */
function ogFromPublic() {
  return {
    name: 'og-from-public',
    transformIndexHtml(html) {
      let text = 'Горизонт Михаила.'
      try {
        const pub = JSON.parse(readFileSync(
          fileURLToPath(new URL('./public/data/public.json', import.meta.url)), 'utf8'))
        const label = pub?.horizon?.current?.label
        const goal = pub?.horizon?.goal?.age
        if (label) text = `Горизонт Михаила ${label}${goal != null ? `, цель ${Math.round(goal)} лет` : ''}.`
      } catch { /* строка без чисел */ }
      return html.replace(/__OG_HORIZON__/g, text)
    },
  }
}

/* ── ПУБЛИЧНЫЕ ДАННЫЕ — ВНУТРИ СТРАНИЦЫ (Д-74, 16.10.2026) ──────────────────
 * Слово владельца: «при загрузке страницы вместо „Ранскеил теперь и для
 * жизни.“ и проч видно какую-то другую фразу артефакт — разберись в чём там
 * зависание». Первый экран ждал `public.json` отдельным запросом, который
 * уходил только после загрузки и запуска бандла; до ответа стояла запасная
 * фраза «Успею 87 · Первый прогон готовится», а сорвавшийся запрос не
 * повторялся, и страница так на ней и оставалась.
 * Теперь сборка кладёт тот же файл в `index.html` блоком
 * <script type="application/json">, как это давно делает однофайловая сборка
 * (`scripts/build-preview.mjs`): данные приходят вместе со страницей, и
 * первый кадр уже с нужной фразой. Сам файл `public.json` по-прежнему
 * публикуется рядом — им пользуется запасной путь `usePublicData`.
 * ⚠ Вкладывается ТОЛЬКО публичный слой. health.json и .enc сюда не идут
 *   никогда: граница Д-45 остаётся той же, что у отдельного файла. */
function publicInline() {
  return {
    name: 'public-inline',
    transformIndexHtml() {
      let raw
      try {
        raw = readFileSync(fileURLToPath(new URL('./public/data/public.json', import.meta.url)), 'utf8')
        JSON.parse(raw)
      } catch {
        return [] // нет файла — страница возьмёт его запросом
      }
      return [
        // Закрыть нужно одно — `</script` внутри данных.
        { tag: 'script', attrs: { type: 'application/json', id: 'kontur-public' }, children: raw.replace(/<\/script/gi, '<\\/script'), injectTo: 'head' },
        { tag: 'script', children: "window.__KONTUR_PUBLIC__ = JSON.parse(document.getElementById('kontur-public').textContent)", injectTo: 'head' },
      ]
    },
  }
}

// base: './' — относительные пути к бандлу и данным.
//
// ⚠ Это не вкусовщина, а условие для GitHub Pages. Project-сайт живёт по адресу
// вида `https://<юзер>.github.io/<репозиторий>/`, то есть НЕ в корне домена.
// При base '/' браузер попросит `/assets/index-*.js` от корня github.io —
// и получит 404 на всём, включая `data/health.json`. Относительная база
// делает сборку переносимой: тот же `dist` открывается и по адресу Pages,
// и с локального диска, и с любого поддиректория.
//
// Плата за относительную базу — нельзя пользоваться History API для маршрутов
// (сервер не знает про наши пути и вернёт 404 при перезагрузке вложенного
// адреса). Поэтому навигация в приложении — состояние, а не URL: разделы
// переключаются реактивной переменной. Для приложения из четырёх вкладок,
// которое живёт на телефоне в полноэкранном режиме, адресной строки всё равно
// нет, и терять нечего.
export default defineConfig({
  base: './',
  plugins: [vue(), ogFromPublic(), publicInline()],
  server: {
    // ⚠ ПОРТ ЗАКРЕПЛЁН (30.08.2026). По умолчанию vite берёт 5173, а занятый
    //   порт молча уступает следующему — адрес приложения начинает зависеть
    //   от того, что запустилось раньше, и одна закладка открывает то один
    //   проект, то другой. У семейства свои номера: 5180 — «Контур»
    //   (медкарта), 5181 — «Успею» (витрина). Соседний gderost — на 5173.
    // ⛔ strictPort: занятый порт роняет запуск с внятной строкой вместо
    //   тихого переезда.
    port: 5180,
    strictPort: true,
  },
  build: {
    target: 'es2020',
    // Один бандл вместо разбиения: приложение целиком меньше 200 КБ, а
    // отдельные чанки на медленной сети дают лишние круги запросов.
    chunkSizeWarningLimit: 800,
  },
})
