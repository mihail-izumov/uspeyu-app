<script setup>
/*
  ЗНАК «Успею» — клетка: число 87, буква У, слово под буквой.

  ⛔ КОМПОНЕНТ НИЧЕГО НЕ РИСУЕТ САМ. Он показывает файл, собранный генератором
     `python3 tools/build_brand.py` из мастера `forecast/targets.md`. Правка
     формы — в генераторе, здесь только размер и подпись. Иначе знак в шапке
     и знак на домашнем экране разъедутся, и заметить это будет некому.

  ⚠⚠ ТРИ СОСТОЯНИЯ, ПОТОМУ ЧТО ДЕТАЛИ ГИБНУТ РАНЬШЕ ФОРМЫ. Пороги замерены на
     отрисовке, а не назначены: внутри клетки число набрано кеглем 15/100
     холста, слово — 12/100. Значит в клетке 34 px цифра выходит по 5
     пикселей, а слово по 4 — пятно, которое читается как дефект отрисовки, а
     не как деталь.
       · `min`  — только буква            → до ~48 px  (фавикон, шапка)
       · `mid`  — число · буква           → от ~64 px  (иконки установки)
       · `full` — число · буква · слово   → от ~96 px  (витрина, OG, обложки)

  ⚠ Плашка знака сплошная и тёмная, поэтому он одинаково стоит и на светлой,
    и на тёмной теме — подложку под него класть не нужно.

  ⚠ `inverse` — тот же знак навыворот: светлая клетка, тёмные число и буква
    (Д-64, слово владельца 15.10.2026: «иконку сделай навыворот, когда на
    тёмном фоне»). Файлы `*-inv.svg` собирает тот же генератор; на светлых
    экранах внутри контура по-прежнему стоит тёмная клетка.

  ⚠ Путь через BASE_URL, а не './icons/…': база сборки относительная (Pages
    живёт в подкаталоге), и относительный путь из компонента считался бы от
    адреса страницы, а не от корня приложения.
*/
const props = defineProps({
  state: { type: String, default: 'mid' },   // full · mid · min
  size: { type: Number, default: 34 },
  inverse: { type: Boolean, default: false },
})

const FILES = { full: 'icon-full.svg', mid: 'icon-mark.svg', min: 'icon.svg' }
const base = import.meta.env.BASE_URL || './'
const file = FILES[props.state] || FILES.mid
const src = `${base}icons/${props.inverse ? file.replace('.svg', '-inv.svg') : file}`
</script>

<template>
  <img
    class="mark"
    :src="src"
    :width="size"
    :height="size"
    alt="Успею"
    decoding="async"
  />
</template>

